#!/usr/bin/env node
// Reads db/data/stock-sheet.csv and db/data/routing.csv, reshapes the wide
// stock sheet (one row per product, 400/310/300 groups side by side) into
// one row per SKU, and writes db/init/02-seed.sql. Node built-ins only.
//
// Usage: node db/make-seed.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const STOCK_CSV = path.join(here, 'data', 'stock-sheet.csv');
const ROUTING_CSV = path.join(here, 'data', 'routing.csv');
const OUT_SQL = path.join(here, 'init', '02-seed.sql');

// --- minimal RFC4180 CSV parser (handles quoted fields, embedded commas,
// embedded quotes doubled as "", and \n or \r\n line endings) ---
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let inQuotes = false;
  let i = 0;

  function endField() {
    row.push(field);
    field = '';
  }
  function endRow() {
    endField();
    rows.push(row);
    row = [];
  }

  while (i < text.length) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 2;
          continue;
        }
        inQuotes = false;
        i += 1;
        continue;
      }
      field += c;
      i += 1;
      continue;
    }
    if (c === '"') {
      inQuotes = true;
      i += 1;
      continue;
    }
    if (c === ',') {
      endField();
      i += 1;
      continue;
    }
    if (c === '\r') {
      i += 1;
      continue;
    }
    if (c === '\n') {
      endRow();
      i += 1;
      continue;
    }
    field += c;
    i += 1;
  }
  // last field/row, if the file doesn't end with a trailing newline
  if (field.length > 0 || row.length > 0) {
    endRow();
  }
  return rows.filter((r) => !(r.length === 1 && r[0] === ''));
}

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function readCsvFile(filePath, label) {
  let text;
  try {
    text = readFileSync(filePath, 'utf8');
  } catch (err) {
    if (err.code === 'ENOENT') {
      console.error(`Missing required file: ${filePath} (${label})`);
      process.exit(1);
    }
    throw err;
  }
  const rows = parseCsv(text);
  const header = rows[0];
  const dataRows = rows.slice(1);
  return { header, dataRows };
}

// --- stock sheet: wide format, 9 columns, 3 groups of (sku, description, qty) ---
const stockFile = readCsvFile(STOCK_CSV, 'stock sheet');
const GROUPS = [
  { name: '400', cols: [0, 1, 2] },
  { name: '310', cols: [3, 4, 5] },
  { name: '300', cols: [6, 7, 8] },
];

const stockRows = [];
for (const row of stockFile.dataRows) {
  for (const group of GROUPS) {
    const [skuCol, descCol, qtyCol] = group.cols;
    const sku = row[skuCol].trim();
    const description = row[descCol].trim();
    const qty = Number.parseInt(row[qtyCol], 10);
    if (sku.length !== 11 || Number.isNaN(qty)) {
      console.error(
        `Malformed stock sheet row (group ${group.name}): sku="${row[skuCol]}" qty="${row[qtyCol]}"`
      );
      process.exit(1);
    }
    stockRows.push({ sku, description, qty });
  }
}

// --- routing sheet: stock prefix, stage, next step, check order ---
const routingFile = readCsvFile(ROUTING_CSV, 'routing rules');
const routingRows = routingFile.dataRows.map((row) => ({
  prefix: row[0].trim(),
  stage: row[1].trim(),
  nextStep: row[2].trim(),
  checkOrder: Number.parseInt(row[3], 10),
}));

// --- write seed SQL ---
const lines = [];
lines.push('-- Generated by db/make-seed.mjs from db/data/*.csv. Do not edit by hand.');
lines.push('-- Fake data only, local test database.');
lines.push('');

lines.push('INSERT INTO stock (sku, description, qty) VALUES');
lines.push(
  stockRows
    .map((r) => `  (${sqlString(r.sku)}, ${sqlString(r.description)}, ${r.qty})`)
    .join(',\n') + ';'
);
lines.push('');

lines.push('INSERT INTO routing (prefix, stage, next_step, check_order) VALUES');
lines.push(
  routingRows
    .map(
      (r) =>
        `  (${sqlString(r.prefix)}, ${sqlString(r.stage)}, ${sqlString(r.nextStep)}, ${r.checkOrder})`
    )
    .join(',\n') + ';'
);
lines.push('');

writeFileSync(OUT_SQL, lines.join('\n'), 'utf8');

console.log(`Wrote ${OUT_SQL}`);
console.log(`stock rows:   ${stockRows.length} (from ${stockFile.dataRows.length} sheet rows x 3 groups)`);
console.log(`routing rows: ${routingRows.length}`);
